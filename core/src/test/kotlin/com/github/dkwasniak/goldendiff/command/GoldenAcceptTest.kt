package com.github.dkwasniak.goldendiff.command

import com.github.dkwasniak.goldendiff.settings.GoldenDiffConfig
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File
import java.nio.file.Files

class GoldenAcceptTest {

    private fun tempProject(): File = Files.createTempDirectory("gd-accept").toFile()

    private fun config(): GoldenDiffConfig = GoldenDiffConfig(
        goldenPaths = listOf("golden"),
        generatedPaths = listOf("generated"),
        generatedFileRegex = "^(.+)_actual\\.png$",
    )

    @Test fun `moves generated bytes onto the golden and removes the generated file`() {
        val root = tempProject()
        val golden = File(root, "golden/LoginScreen.png").apply { parentFile.mkdirs(); writeBytes(byteArrayOf(1, 1, 1)) }
        val generated = File(root, "generated/LoginScreen_actual.png").apply { parentFile.mkdirs(); writeBytes(byteArrayOf(2, 2, 2)) }

        val result = GoldenAccept.accept(golden, config(), root)

        assertTrue(result.isSuccess)
        assertEquals(generated.canonicalPath, result.getOrNull()?.canonicalPath)
        assertArrayEquals(byteArrayOf(2, 2, 2), golden.readBytes())
        assertFalse("generated _actual must be removed after accept", generated.exists())
    }

    @Test fun `fails when there is no generated counterpart`() {
        val root = tempProject()
        val golden = File(root, "golden/LoginScreen.png").apply { parentFile.mkdirs(); writeBytes(byteArrayOf(1)) }

        val result = GoldenAccept.accept(golden, config(), root)

        assertTrue(result.isFailure)
        val failure = (result.exceptionOrNull() as? GoldenAccept.AcceptException)?.failure
        assertTrue(failure is GoldenAccept.Failure.NoGeneratedCounterpart)
    }

    @Test fun `canAccept reflects counterpart presence`() {
        val root = tempProject()
        val golden = File(root, "golden/LoginScreen.png").apply { parentFile.mkdirs(); writeBytes(byteArrayOf(1)) }

        assertFalse(GoldenAccept.canAccept(golden, config(), root))
        File(root, "generated/LoginScreen_actual.png").apply { parentFile.mkdirs(); writeBytes(byteArrayOf(2)) }
        assertTrue(GoldenAccept.canAccept(golden, config(), root))
    }

    private fun assertEquals(expected: Any?, actual: Any?) = org.junit.Assert.assertEquals(expected, actual)
}
