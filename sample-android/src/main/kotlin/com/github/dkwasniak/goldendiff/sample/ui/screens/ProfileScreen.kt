@Composable
fun ProfileScreen(modifier: Modifier = Modifier) {
    Surface(modifier = modifier.fillMaxSize(), color = MaterialTheme.colorScheme.background) {
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(24.dp),
            horizontalAlignment = Alignment.CenterHorizontally,
        ) {
            Box(
                modifier = Modifier
                    .size(88.dp)
                    .clip(CircleShape)
                    .padding(4.dp),
            ) {
                Surface(color = MaterialTheme.colorScheme.secondary, modifier = Modifier.fillMaxSize()) {}
            }
            Text(
                text = "Ada Lovelace",
                style = MaterialTheme.typography.titleLarge,
                fontWeight = FontWeight.Bold,
                modifier = Modifier.padding(top = 16.dp),
            )
            Text(
                text = "Mathematician & analyst",
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(top = 24.dp),
                horizontalArrangement = Arrangement.SpaceEvenly,
            ) {
                ProfileStat(label = "Projects", value = "12")
                ProfileStat(label = "Followers", value = "1.4k")
                ProfileStat(label = "Following", value = "87")
